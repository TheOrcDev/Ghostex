/// The emoji a shortcode (without its colons) names.
pub(crate) fn emoji_for(name: &str) -> Option<&'static str> {
    EMOJI
        .binary_search_by(|(code, _)| (*code).cmp(name))
        .ok()
        .map(|index| EMOJI[index].1)
}
